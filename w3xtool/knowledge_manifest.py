def format_knowledge_manifest() -> str:
    """Return the knowledge-pack artifact directory as TSV."""
    rows = ["主题\t文件\t用途"]
    rows.extend(
        "\t".join((_tsv(topic), _tsv(path), _tsv(detail)))
        for topic, path, detail in _ROWS
    )
    return "\n".join(rows) + "\n"
