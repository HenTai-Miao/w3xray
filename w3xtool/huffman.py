# ---------------------------------------------------------------------------
# 比特流（LSB 优先，对应 StormLib TInputStream）
# ---------------------------------------------------------------------------

class _InputStream:
    __slots__ = ("data", "pos", "end", "bit_buffer", "bit_count")

    def __init__(self, data: bytes):
        self.data = data
        self.pos = 0
        self.end = len(data)
        self.bit_buffer = 0
        self.bit_count = 0

    def get_1_bit(self):
        """返回 (ok, bit)。"""
        if self.bit_count == 0:
            if self.pos >= self.end:
                return False, 0
            self.bit_buffer = self.data[self.pos]
            self.pos += 1
            self.bit_count = 8
        bit = self.bit_buffer & 0x01
        self.bit_buffer >>= 1
        self.bit_count -= 1
        return True, bit

    def get_8_bits(self):
        """返回 (ok, byte)。"""
        if self.bit_count < 8:
            if self.pos >= self.end:
                return False, 0
            self.bit_buffer |= self.data[self.pos] << self.bit_count
            self.pos += 1
            self.bit_count += 8
        value = self.bit_buffer & 0xFF
        self.bit_buffer >>= 8
        self.bit_count -= 8
        return True, value


# ---------------------------------------------------------------------------
# Huffman 树（对应 StormLib THuffmannTree，仅解压路径）
# ---------------------------------------------------------------------------

class _Item:
    __slots__ = ("pNext", "pPrev", "DecompressedValue", "Weight", "pParent", "pChildLo")

    def __init__(self):
        self.pNext = None
        self.pPrev = None
        self.DecompressedValue = 0
        self.Weight = 0
        self.pParent = None
        self.pChildLo = None


INSERT_AFTER = 1
INSERT_BEFORE = 2


class _HuffmannTree:
    def __init__(self):
        # ListHead 是循环双向链表的哨兵
        self.head = _Item()
        self.head.pNext = self.head
        self.head.pPrev = self.head
        self.min_valid_value = 1
        # 仅解压用的快速链路这里不做（quick-link 仅为加速，可省略而不影响正确性）
        self.items_by_byte = [None] * 258  # 0..0x101

    # --- 链表操作 ---
    def _remove_item(self, item):
        if item.pNext is not None:
            item.pPrev.pNext = item.pNext
            item.pNext.pPrev = item.pPrev
            item.pNext = None
            item.pPrev = None

    def _link_two_items(self, item1, item2):
        # 把 item2 插入到 item1 之后
        item2.pNext = item1.pNext
        item2.pPrev = item1.pNext.pPrev
        item1.pNext.pPrev = item2
        item1.pNext = item2

    def _insert_item(self, new_item, insert_point, p_insert_point):
        self._remove_item(new_item)
        if p_insert_point is None:
            p_insert_point = self.head
        if insert_point == INSERT_AFTER:
            self._link_two_items(p_insert_point, new_item)
        elif insert_point == INSERT_BEFORE:
            self._link_two_items(p_insert_point.pPrev, new_item)

    def _find_higher_or_equal_item(self, item, weight):
        if item is not None:
            while item is not self.head:
                if item.Weight >= weight:
                    return item
                item = item.pPrev
        return self.head

    def _create_new_item(self, decompressed_value, weight, insert_point):
        new_item = _Item()
        self._insert_item(new_item, insert_point, None)
        new_item.DecompressedValue = decompressed_value
        new_item.Weight = weight
        new_item.pParent = None
        new_item.pChildLo = None
        return new_item

    def _fixup_item_pos_by_weight(self, new_item, max_weight):
        if new_item.Weight < max_weight:
            higher = self._find_higher_or_equal_item(self.head.pPrev, new_item.Weight)
            self._remove_item(new_item)
            self._link_two_items(higher, new_item)
        else:
            max_weight = new_item.Weight
        return max_weight

    def build_tree(self, data_type):
        self.items_by_byte = [None] * 258
        max_weight = 0

        data_type &= 0x0F
        if data_type >= MAX_DATA_TYPE:
            return False
        table = DataDistributions[data_type]

        for i in range(0x100):
            if table[i] != 0:
                new_item = self._create_new_item(i, table[i], INSERT_AFTER)
                self.items_by_byte[i] = new_item
                max_weight = self._fixup_item_pos_by_weight(new_item, max_weight)

        # 末尾插入两个终止条目
        self.items_by_byte[0x100] = self._create_new_item(0x100, 1, INSERT_BEFORE)
        self.items_by_byte[0x101] = self._create_new_item(0x101, 1, INSERT_BEFORE)

        # 自底向上建树
        child_lo = self.head.pPrev
        while child_lo is not self.head:
            child_hi = child_lo.pPrev
            if child_hi is self.head:
                break
            new_item = self._create_new_item(0, child_hi.Weight + child_lo.Weight, INSERT_AFTER)
            if new_item is None:
                return False
            child_lo.pParent = new_item
            child_hi.pParent = new_item
            new_item.pChildLo = child_lo
            max_weight = self._fixup_item_pos_by_weight(new_item, max_weight)
            child_lo = child_hi.pPrev

        self.min_valid_value = 1
        return True

    def inc_weights_and_rebalance(self, item):
        while item is not None:
            item.Weight += 1

            higher_item = self._find_higher_or_equal_item(item.pPrev, item.Weight)
            child_hi = higher_item.pNext

            if child_hi is not item:
                # 把 child_hi 移到 item 右边
                self._remove_item(child_hi)
                self._link_two_items(item, child_hi)

                # 把 item 移到 higher_item 之后
                self._remove_item(item)
                self._link_two_items(higher_item, item)

                child_lo = child_hi.pParent.pChildLo
                parent = item.pParent
                if parent.pChildLo is item:
                    parent.pChildLo = child_hi
                if child_lo is child_hi:
                    child_hi.pParent.pChildLo = item
                parent = item.pParent
                item.pParent = child_hi.pParent
                child_hi.pParent = parent

                self.min_valid_value += 1

            item = item.pParent

    def insert_new_branch_and_rebalance(self, value1, value2):
        last_item = self.head.pPrev
        child_hi = self._create_new_item(value1, last_item.Weight, INSERT_BEFORE)
        if child_hi is not None:
            child_hi.pParent = last_item
            self.items_by_byte[value1] = child_hi

            child_lo = self._create_new_item(value2, 0, INSERT_BEFORE)
            if child_lo is not None:
                child_lo.pParent = last_item
                last_item.pChildLo = child_lo
                self.items_by_byte[value2] = child_lo

                self.inc_weights_and_rebalance(child_lo)
                return True
        return False

    def decode_one_byte(self, is_):
        # 简化版（不含 quick-link 加速），始终从根开始走
        if self.head.pNext is self.head:
            return HUFF_DECOMPRESS_ERROR
        item = self.head.pNext

        while item.pChildLo is not None:
            ok, bit = is_.get_1_bit()
            if not ok:
                return HUFF_DECOMPRESS_ERROR
            item = item.pChildLo.pPrev if bit else item.pChildLo

        return item.DecompressedValue

    def decompress(self, out_size, is_):
        out = bytearray()
        if out_size == 0:
            return bytes(out)

        ok, data_type = is_.get_8_bits()
        if not ok:
            return bytes(out)
        is_sparse = (data_type == 0x00)

        if not self.build_tree(data_type):
            return bytes(out)

        while True:
            value = self.decode_one_byte(is_)
            if value == 0x100:
                break
            if value == HUFF_DECOMPRESS_ERROR:
                return bytes(out)

            if value == 0x101:
                ok, value = is_.get_8_bits()
                if not ok:
                    return bytes(out)
                if not self.insert_new_branch_and_rebalance(
                        self.head.pPrev.DecompressedValue, value):
                    return bytes(out)
                if not is_sparse:
                    self.inc_weights_and_rebalance(self.items_by_byte[value])

            if len(out) >= out_size:
                break
            out.append(value & 0xFF)

            if is_sparse:
                self.inc_weights_and_rebalance(self.items_by_byte[value])

        return bytes(out)


def huff_decompress(data: bytes, out_size: int) -> bytes:
    """data 以 DataType 字节开头（即 MPQ 扇区去掉 0x01 压缩掩码后的内容）。

    返回解压后的字节，长度不超过 out_size（硬上限，防解压炸弹）。
    """
    if not data:
        return b""
    is_ = _InputStream(data)
    tree = _HuffmannTree()
    return tree.decompress(max(0, out_size), is_)
